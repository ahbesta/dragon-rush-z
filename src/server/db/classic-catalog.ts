const attrs = (
  strength: number,
  defense: number,
  speed: number,
  endurance: number,
  kiControl = strength,
): Attributes => ({ strength, defense, speed, endurance, kiControl });
const affinity = (
  primary: keyof Allocation,
  secondary: keyof Allocation,
  a = 1.25,
  b = 1.1,
): Allocation => ({
  strength: 1,
  defense: 1,
  speed: 1,
  endurance: 1,
  kiControl: 1,
  [primary]: a,
  [secondary]: b,
});
const flag = (id: string): Requirements => ({ flags: [`quest:${id}`] });
const hit = (label: string, techniqueId = "soco", multiplier = 1): EnemyMove => ({
  kind: "attack",
  label,
  techniqueId,
  multiplier,
});
const guard: EnemyMove = { kind: "guard", label: "Assume uma postura defensiva" };
const charge: EnemyMove = { kind: "charge", label: "Concentra energia: prepare sua defesa!" };
const poison: EnemyMove = {
  kind: "attack",
  label: "Prepara um golpe venenoso",
  techniqueId: "soco",
  status: "poison",
};
const patterns = {
  basic: [hit("Avança para atacar"), hit("Prepara um golpe forte", "chute", 1.1), guard],
  beast: [hit("Prepara uma mordida"), charge, hit("Vai investir com toda a força", "chute", 1.8)],
  martial: [
    hit("Prepara um golpe técnico", "chute"),
    guard,
    charge,
    hit("Prepara uma investida poderosa", "jan-ken", 1.3),
  ],
  ki: [
    hit("Prepara uma rajada", "rajada-ki"),
    guard,
    charge,
    hit("Vai disparar energia concentrada", "rajada-ki", 2),
  ],
};
function enemy(
  id: string,
  name: string,
  level: number,
  areaFlag: Requirements = {},
  pattern = patterns.basic,
  boss = false,
  artId = "soldado-red-ribbon",
): EnemyDefinition {
  const strength = Math.round(8 + level * 1.6);
  return {
    id,
    name,
    description: boss
      ? `Um desafio decisivo: observe os movimentos de ${name} e prepare seus itens.`
      : `Adversário da campanha clássica. Observe sua intenção antes de atacar.`,
    level,
    attributes: attrs(strength, 5 + level, 7 + level, 8 + level, 8 + level * 1.4),
    maxHp: Math.round(((boss ? 160 : 65) + level * (boss ? 24 : 13)) * (boss ? 1.3 : 1)),
    maxKi: 50 + level * 6,
    xpReward: boss ? 100 + level * 15 : 20 + level * 8,
    zeniReward: boss ? 50 + level * 10 : 10 + level * 3,
    boss,
    requirements: { minLevel: Math.max(1, level - (boss ? 1 : 2)), ...areaFlag },
    techniqueIds: [...new Set(pattern.flatMap((p) => (p.techniqueId ? [p.techniqueId] : [])))],
    pattern,
    phases: boss
      ? [
          {
            threshold: 0.5,
            name: `Determinação de ${name}`,
            strengthMultiplier: 1.2,
            pattern: [charge, ...pattern.filter((p) => p.kind === "attack"), guard],
          },
        ]
      : [],
    artId,
    guaranteedItem: boss ? `trofeu-${id}` : undefined,
  };
}
const equipment = (
  id: string,
  name: string,
  slot: ItemDefinition["slot"],
  effects: ItemDefinition["effects"],
  minLevel = 1,
  rarity: ItemDefinition["rarity"] = "common",
  source = "Lojas e fabricação nas vilas",
): ItemDefinition => ({
  id,
  name,
  description: source,
  slot,
  effects,
  requirements: { minLevel },
  type: "equipment",
  rarity,
  sellPrice: rarity === "epic" ? 80 : rarity === "rare" ? 35 : 12,
  source,
});
const consumable = (
  id: string,
  name: string,
  effects: ItemDefinition["effects"],
  description: string,
  rarity: ItemDefinition["rarity"] = "common",
): ItemDefinition => ({
  id,
  name,
  description,
  type: "consumable",
  rarity,
  slot: null,
  effects,
  requirements: {},
  sellPrice: rarity === "rare" ? 20 : 5,
  source: id === "semente-deuses" ? "Provas e trocas com Karin" : "Lojas, fabricação e drops",
});
