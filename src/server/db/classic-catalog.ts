function quest(
  id: string,
  chapterId: string,
  name: string,
  description: string,
  requirements: Requirements,
  objectives: QuestDefinition["objectives"],
  xp: number,
  zeni: number,
  rewardItems?: { itemId: string; quantity: number }[],
  flags?: string[],
): QuestDefinition {
  return {
    id,
    chapterId,
    name,
    description,
    requirements,
    objectives,
    rewards: { xp, zeni, items: rewardItems, flags },
  };
}
